import * as z from "zod";
import { downloadEntrySchema } from "@/configuration/downloads";

export const schema = z
  .object({
    list: z
      .array(
        z
          .object({
            type: z.enum(["notice", "publication", "activity"]).meta({
              title: "Type",
              description:
                "The type of content item: notice, publication, or activity. This is set automatically based on the page you're editing.",
            }),
            id: z.string().min(1, "ID is required.").meta({
              title: "ID",
              description:
                "A hidden stable identifier generated by the setup page.",
            }),
            slugs: z
              .array(
                z
                  .object({
                    isActive: z.boolean().default(true).meta({
                      title: "Is Active",
                      description:
                        "Whether this slug is active and should be used to access the item.",
                    }),
                    slug: z.string().min(1, "Slug is required.").meta({
                      title: "Slug",
                      description:
                        "A unique URL slug generated from the item title.",
                    }),
                  })
                  .meta({
                    title: "Slug",
                    description:
                      "A unique URL slug generated from the item title.",
                  }),
              )
              .default([])
              .meta({
                title: "Slugs",
                description:
                  "The list of slugs including historical ones that can be used to access the item.",
              }),
            title: z.string().min(1, "Title is required.").meta({
              title: "Title",
              description:
                "The headline shown on the card and at the top of the detail page.",
            }),
            summary: z.string().min(1, "Summary is required.").meta({
              title: "Summary",
              description:
                "A concise description shown on the card and used for the item's search result description.",
            }),
            date: z.string().min(1, "Date is required.").meta({
              title: "Date",
              description:
                "The publication or event date shown to readers. Use a clear date such as 2026-01-15.",
            }),
            category: z.string().optional().meta({
              title: "Category",
              description:
                "An optional category used to group or filter items.",
            }),
            author: z.string().optional().meta({
              title: "Author",
              description:
                "The author of this content item. This field is hidden in the UI and taken from the GitHub account.",
            }),
            associatedOrganisationIds: z
              .array(
                z.string().min(1, "Organisation ID is required.").meta({
                  title: "Organisation ID",
                  description:
                    "The ID of an organisation associated with this content item.",
                }),
              )
              .default([])
              .meta({
                title: "Associated Organisations",
                description:
                  "Select existing organisations that are associated with this content item.",
              }),
            attachments: z.array(downloadEntrySchema).default([]).meta({
              title: "Attachments",
              description:
                "Files attached to this content, with a name, URL, and optional size. Only available for notices.",
            }),
            coverImage: z.string().optional().meta({
              title: "Cover Image",
              description:
                "An optional cover image shown on the card. Only available for activity and publications.",
            }),
          })
          .meta({
            title: "Content Item",
            description:
              "Metadata for a content item whose rich-text HTML is stored in a separate file named after its ID.",
          }),
      )
      .default([])
      .meta({
        title: "Content Items",
        description:
          "The list of content items (notices, publications, or activities) displayed on the listing page.",
      }),
  })
  .meta({
    title: "Contents Configuration",
    description:
      "Configuration for content listing pages — notices, publications, and activities.",
  });

export const buildSchema = schema.extend({}).partial();

export type TInput = z.input<typeof schema>;
export type TOutput = z.output<typeof schema>;
export type TModel = TOutput;

export const defaultValues: TInput = {
  list: [],
};
